export type UIKey = keyof typeof es

export const ui: Record<Lang, Record<UIKey, string>> = { es, en }

/** Deriva el idioma desde un pathname (para islands Vue en el cliente). */
export function getLangFromPath(pathname: string): Lang {
  return pathname === '/en' || pathname.startsWith('/en/') ? 'en' : 'es'
}

/** Deriva el idioma desde Astro.currentLocale (undefined = root = es). */
export function getLangFromLocale(locale: string | undefined): Lang {
  return locale === 'en' ? 'en' : 'es'
}

/**
 * Devuelve una función de traducción `t(key, params?)`.
 * Soporta interpolación simple de `{param}` en el string.
 */
export function useT(lang: Lang) {
  return (key: UIKey, params?: Record<string, string | number>): string => {
    let str = ui[lang][key] ?? ui[DEFAULT_LANG][key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(`{${k}}`, String(v))
      }
    }
    return str
  }
}
